-- Palawan Paraiso booking schema
-- The JSON payload on bookings keeps the current frontend compatible while the
-- supporting tables mirror the ERD and leave room for normalized data later.

create table if not exists public.customer_account (
  customer_id bigint generated by default as identity primary key,
  username text unique,
  full_name text not null,
  email text,
  phone text,
  created_at timestamptz not null default now()
);

create table if not exists public.catalogue_item (
  catalogue_item_id bigint generated by default as identity primary key,
  item_type text not null check (item_type in ('room', 'cottage', 'restaurant', 'venue')),
  name text not null,
  description text,
  base_price numeric(12, 2) not null default 0,
  billing_unit text,
  active boolean not null default true
);

create table if not exists public.room_type (
  room_type_id bigint generated by default as identity primary key,
  catalogue_item_id bigint not null references public.catalogue_item(catalogue_item_id) on delete cascade,
  room_category text not null,
  capacity integer not null default 1 check (capacity > 0)
);

create table if not exists public.cottage_type (
  cottage_type_id bigint generated by default as identity primary key,
  catalogue_item_id bigint not null references public.catalogue_item(catalogue_item_id) on delete cascade,
  cottage_category text not null,
  capacity integer not null default 1 check (capacity > 0)
);

create table if not exists public.restaurant_menu (
  menu_id bigint generated by default as identity primary key,
  catalogue_item_id bigint not null references public.catalogue_item(catalogue_item_id) on delete cascade,
  meal_period text not null
);

create table if not exists public.venue_type (
  venue_type_id bigint generated by default as identity primary key,
  catalogue_item_id bigint not null references public.catalogue_item(catalogue_item_id) on delete cascade,
  venue_category text not null,
  event_notes text
);

create table if not exists public.bookings (
  id text primary key,
  user_id text not null,
  customer_id bigint references public.customer_account(customer_id) on delete set null,
  data jsonb not null,
  completed boolean not null default false,
  booking_status text not null default 'ongoing' check (booking_status in ('ongoing', 'completed', 'cancelled')),
  start_at timestamptz,
  end_at timestamptz,
  total_price numeric(12, 2),
  downpayment_amount numeric(12, 2),
  balance_amount numeric(12, 2),
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  cancelled_at timestamptz
);

-- Safe migration for the original one-table schema.
-- Passwords belong only to Supabase Auth, where they are securely hashed.
-- Do not store or duplicate passwords in public.customer_account.
 
alter table public.bookings add column if not exists customer_id bigint references public.customer_account(customer_id) on delete set null;
alter table public.bookings add column if not exists booking_status text not null default 'ongoing';
alter table public.bookings add column if not exists start_at timestamptz;
alter table public.bookings add column if not exists end_at timestamptz;
alter table public.bookings add column if not exists total_price numeric(12, 2);
alter table public.bookings add column if not exists downpayment_amount numeric(12, 2);
alter table public.bookings add column if not exists balance_amount numeric(12, 2);
alter table public.bookings add column if not exists completed_at timestamptz;
alter table public.bookings add column if not exists cancelled_at timestamptz;

update public.bookings
set booking_status = case when completed then 'completed' else 'ongoing' end
where booking_status is null or booking_status = '';

create table if not exists public.booking_item (
  booking_item_id bigint generated by default as identity primary key,
  booking_id text not null references public.bookings(id) on delete cascade,
  catalogue_item_id bigint references public.catalogue_item(catalogue_item_id) on delete set null,
  quantity integer not null default 1 check (quantity > 0),
  scheduled_date date,
  start_time time,
  end_time time,
  unit_price numeric(12, 2) not null default 0,
  line_total numeric(12, 2) not null default 0
);

create table if not exists public.payment (
  payment_id bigint generated by default as identity primary key,
  booking_id text not null references public.bookings(id) on delete cascade,
  amount numeric(12, 2) not null default 0,
  payment_type text not null,
  payment_status text not null default 'pending',
  paid_at timestamptz,
  transaction_reference text
);

create table if not exists public.confirmation (
  confirmation_id bigint generated by default as identity primary key,
  booking_id text not null unique references public.bookings(id) on delete cascade,
  confirmed_by_customer boolean not null default false,
  confirmation_status text not null default 'pending',
  confirmed_at timestamptz
);

create table if not exists public.receipt (
  receipt_id bigint generated by default as identity primary key,
  booking_id text not null unique references public.bookings(id) on delete cascade,
  receipt_number text not null unique,
  total_amount numeric(12, 2) not null default 0,
  downpayment_amount numeric(12, 2) not null default 0,
  balance_amount numeric(12, 2) not null default 0,
  issued_at timestamptz not null default now(),
  stored_in_account boolean not null default true
);

create index if not exists bookings_user_status_idx on public.bookings(user_id, booking_status);
create index if not exists bookings_created_at_idx on public.bookings(created_at desc);

