-- Create a customer profile whenever Supabase Auth creates a user.
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.customer_account (username, full_name, email, phone)
  values (
    new.id::text,
    coalesce(nullif(trim(concat(new.raw_user_meta_data ->> 'firstName', ' ', new.raw_user_meta_data ->> 'lastName')), ''), 'Guest User'),
    new.email,
    coalesce(new.raw_user_meta_data ->> 'phone', new.phone)
  )
  on conflict (username) do update set
    full_name = excluded.full_name,
    email = excluded.email,
    phone = excluded.phone;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_auth_user();

-- Backfill Auth users that were created before this trigger was installed.
insert into public.customer_account (username, full_name, email, phone)
select
  u.id::text,
  coalesce(nullif(trim(concat(u.raw_user_meta_data ->> 'firstName', ' ', u.raw_user_meta_data ->> 'lastName')), ''), 'Guest User'),
  u.email,
  coalesce(u.raw_user_meta_data ->> 'phone', u.phone)
from auth.users u
on conflict (username) do update set
  full_name = excluded.full_name,
  email = excluded.email,
  phone = excluded.phone;
