create or replace function public.get_booking_availability(
  p_item_key text,
  p_from_date date,
  p_to_date date
)
returns table (
  item_key text,
  unit_label text,
  group_label text,
  start_date date,
  end_date date,
  start_time time,
  end_time time
)
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  if p_item_key is null or p_from_date is null or p_to_date is null or p_to_date <= p_from_date
    or p_to_date - p_from_date > 370 then
    raise exception 'Invalid availability date range';
  end if;

  return query
  select
    u.app_item_key,
    u.unit_label,
    u.group_label,
    (a.starts_at at time zone 'Asia/Manila')::date,
    greatest(
      (a.ends_at at time zone 'Asia/Manila')::date,
      (a.starts_at at time zone 'Asia/Manila')::date + 1
    ),
    (a.starts_at at time zone 'Asia/Manila')::time,
    (a.ends_at at time zone 'Asia/Manila')::time
  from public.booking_inventory_allocation a
  join public.booking_inventory_unit u on u.inventory_unit_id = a.inventory_unit_id
  where u.active
    and a.released_at is null
    and (p_item_key is null or u.app_item_key = p_item_key)
    and a.starts_at < p_to_date::timestamp at time zone 'Asia/Manila'
    and a.ends_at > p_from_date::timestamp at time zone 'Asia/Manila';
end;
$$;

create or replace function public.get_booking_inventory_summary(p_date date)
returns table (
  item_key text,
  unit_type text,
  total_units integer,
  available_units integer
)
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  day_start timestamptz;
  day_end timestamptz;
begin
  if p_date is null then
    raise exception 'Availability date is required';
  end if;
  day_start := p_date::timestamp at time zone 'Asia/Manila';
  day_end := (p_date + 1)::timestamp at time zone 'Asia/Manila';

  return query
  select
    u.app_item_key,
    c.item_type,
    count(distinct u.inventory_unit_id)::integer,
    count(distinct u.inventory_unit_id) filter (where a.inventory_unit_id is null)::integer
  from public.booking_inventory_unit u
  join public.catalogue_item c on c.app_item_key = u.app_item_key and c.active
  left join public.booking_inventory_allocation a
    on a.inventory_unit_id = u.inventory_unit_id
    and a.released_at is null
    and a.starts_at < day_end
    and a.ends_at > day_start
  where u.active
  group by u.app_item_key, c.item_type;
end;
$$;

create or replace function public.create_customer_booking(p_booking jsonb)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  user_id_value uuid := auth.uid();
  request_id_value text;
  category_value text;
  item_key_value text;
  guest_value jsonb;
  guest_count integer;
  capacity_value integer;
  item_price numeric(12, 2);
  item_type_value text;
  base_total numeric(12, 2);
  total_value numeric(12, 2);
  fee_value numeric(12, 2);
  balance_value numeric(12, 2);
  reservation_date date;
  check_in date;
  check_out date;
  starts_at_value timestamptz;
  ends_at_value timestamptz;
  start_time_value time;
  end_time_value time;
  unit_label_value text;
  selected_unit bigint;
  unit_id_value bigint;
  required_units integer;
  allocated_units integer := 0;
  table_count integer;
  payment_method text;
  payment_plan text;
  downpayment_option text;
  receipt_number_value text;
  booking_id_value text;
  booking_data jsonb;
  existing_data jsonb;
  add_ons jsonb;
begin
  if user_id_value is null then
    raise exception 'Sign in is required to make a booking';
  end if;
  if jsonb_typeof(p_booking) <> 'object' then
    raise exception 'Invalid booking details';
  end if;

  request_id_value := nullif(p_booking ->> 'id', '');
  if request_id_value is null or length(request_id_value) > 80 then
    raise exception 'Invalid booking request identifier';
  end if;

  select b.data into existing_data
  from public.bookings b
  where b.user_id = user_id_value::text
    and b.client_request_id = request_id_value;
  if found then
    return existing_data;
  end if;

  category_value := p_booking ->> 'category';
  item_key_value := p_booking ->> 'itemId';
  guest_value := p_booking -> 'g';
  if category_value is null or category_value not in ('room', 'cottage', 'restaurant', 'venue')
    or item_key_value is null or jsonb_typeof(guest_value) is distinct from 'object' then
    raise exception 'Invalid booking category or item';
  end if;

  select c.item_type, c.base_price, c.guest_capacity
    into item_type_value, item_price, capacity_value
  from public.catalogue_item c
  where c.app_item_key = item_key_value and c.active;
  if not found or item_type_value <> category_value then
    raise exception 'The selected item is unavailable';
  end if;

  if coalesce(length(trim(guest_value ->> 'firstName')), 0) = 0
    or coalesce(length(trim(guest_value ->> 'lastName')), 0) = 0
    or coalesce(length(trim(guest_value ->> 'email')), 0) = 0
    or position('@' in (guest_value ->> 'email')) < 2
    or coalesce(length(trim(guest_value ->> 'phone')), 0) = 0 then
    raise exception 'Guest name, email, and phone are required';
  end if;
  guest_count := coalesce((guest_value ->> 'pax')::integer, 0);
  if guest_count < 1 or guest_count > capacity_value then
    raise exception 'Guest count exceeds the selected item capacity';
  end if;

  payment_method := p_booking ->> 'method';
  if payment_method is null or payment_method not in ('credit', 'debit', 'gcash', 'maya', 'visa', 'resort') then
    raise exception 'Invalid payment method';
  end if;
  payment_plan := p_booking ->> 'payPlan';
  if payment_plan is null or payment_plan not in ('full', 'downpayment') then
    raise exception 'Invalid payment plan';
  end if;
  downpayment_option := nullif(p_booking ->> 'downpayOption', '');
  if payment_plan = 'downpayment'
    and (downpayment_option is null or downpayment_option not in ('on-arrival', 'follow-up')) then
    raise exception 'Select a downpayment arrangement';
  end if;

  if category_value in ('room', 'cottage') then
    check_in := nullif(p_booking ->> 'checkIn', '')::date;
    check_out := nullif(p_booking ->> 'checkOut', '')::date;
    unit_label_value := nullif(p_booking ->> 'unitLabel', '');
    if check_in is null or check_out is null or check_in < (now() at time zone 'Asia/Manila')::date
      or check_out <= check_in or unit_label_value is null then
      raise exception 'Select valid stay dates and an available unit';
    end if;
    starts_at_value := check_in::timestamp at time zone 'Asia/Manila';
    ends_at_value := check_out::timestamp at time zone 'Asia/Manila';
    base_total := item_price * (check_out - check_in);

  elsif category_value = 'restaurant' then
    reservation_date := nullif(p_booking ->> 'resDate', '')::date;
    if reservation_date is null or reservation_date < (now() at time zone 'Asia/Manila')::date then
      raise exception 'Select a valid restaurant reservation date';
    end if;
    case item_key_value
      when 'breakfast' then start_time_value := time '06:00'; end_time_value := time '10:00';
      when 'lunch' then start_time_value := time '11:00'; end_time_value := time '14:30';
      when 'dinner' then start_time_value := time '18:00'; end_time_value := time '22:00';
      else raise exception 'The selected meal period is unavailable';
    end case;
    starts_at_value := (reservation_date + start_time_value)::timestamp at time zone 'Asia/Manila';
    ends_at_value := (reservation_date + end_time_value)::timestamp at time zone 'Asia/Manila';
    table_count := coalesce((p_booking ->> 'tables')::integer, 0);
    if p_booking ->> 'resType' = 'Whole Restaurant' then
      required_units := (select count(*) from public.booking_inventory_unit u where u.app_item_key = item_key_value and u.active);
      base_total := item_price * capacity_value;
    else
      if p_booking ->> 'resType' is null
        or p_booking ->> 'resType' not in ('Solo', 'Couple', 'Family', 'Group')
        or table_count < 1 then
        raise exception 'Select a valid restaurant reservation type and table count';
      end if;
      required_units := table_count;
      base_total := item_price * guest_count;
    end if;

  else
    reservation_date := nullif(p_booking ->> 'resDate', '')::date;
    start_time_value := nullif(p_booking ->> 'startTime', '')::time;
    end_time_value := nullif(p_booking ->> 'endTime', '')::time;
    unit_label_value := nullif(p_booking ->> 'unitLabel', '');
    if reservation_date is null or reservation_date < (now() at time zone 'Asia/Manila')::date
      or start_time_value is null or end_time_value is null
      or end_time_value <= start_time_value or unit_label_value is null then
      raise exception 'Select a valid event date, time, and available venue unit';
    end if;
    starts_at_value := (reservation_date + start_time_value)::timestamp at time zone 'Asia/Manila';
    ends_at_value := (reservation_date + end_time_value)::timestamp at time zone 'Asia/Manila';
    add_ons := coalesce(p_booking -> 'addOns', '{}'::jsonb);
    base_total := item_price
      + case when coalesce((add_ons ->> 'catering')::boolean, false) then 5000 else 0 end
      + case when coalesce((add_ons ->> 'rooms')::boolean, false) then 3000 else 0 end
      + case when coalesce((add_ons ->> 'cottages')::boolean, false) then 2000 else 0 end;
  end if;

  if category_value in ('restaurant', 'venue') and starts_at_value <= now() then
    raise exception 'The selected booking time has already started';
  end if;
  if category_value <> 'restaurant' then
    required_units := 1;
  end if;
  if required_units < 1 then
    raise exception 'No bookable inventory exists for this item';
  end if;

  total_value := round(base_total, 2);
  fee_value := case when payment_plan = 'full' then total_value else round(total_value * 0.30, 0) end;
  balance_value := total_value - fee_value;
  receipt_number_value := 'RCP-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 12));
  booking_id_value := gen_random_uuid()::text;

  -- Lock every unit for this item in a stable order before checking occupancy.
  for unit_id_value in
    select u.inventory_unit_id
    from public.booking_inventory_unit u
    where u.app_item_key = item_key_value and u.active
    order by u.inventory_unit_id
  loop
    perform 1
    from public.booking_inventory_unit u
    where u.inventory_unit_id = unit_id_value
    for update;
  end loop;

  -- A retried network request returns the already-created booking.
  select b.data into existing_data
  from public.bookings b
  where b.user_id = user_id_value::text
    and b.client_request_id = request_id_value;
  if found then
    return existing_data;
  end if;

  booking_data := p_booking || jsonb_build_object(
    'id', booking_id_value,
    'receiptId', receipt_number_value,
    'createdAt', clock_timestamp(),
    'userId', user_id_value::text,
    'total', total_value,
    'fee', fee_value,
    'balance', balance_value,
    'paymentStatus', 'pending',
    'booking_status', 'ongoing',
    'nights', case when category_value in ('room', 'cottage') then check_out - check_in else 0 end
  );

  insert into public.bookings (
    id, user_id, customer_id, client_request_id, data, booking_status,
    start_at, end_at, total_price, downpayment_amount, balance_amount
  )
  values (
    booking_id_value,
    user_id_value::text,
    (select ca.customer_id from public.customer_account ca where ca.username = user_id_value::text),
    request_id_value,
    booking_data,
    'ongoing',
    starts_at_value,
    ends_at_value,
    total_value,
    fee_value,
    balance_value
  );

  if category_value = 'restaurant' then
    allocated_units := 0;
    for selected_unit in
      select u.inventory_unit_id
      from public.booking_inventory_unit u
      where u.app_item_key = item_key_value
        and u.active
        and not exists (
          select 1 from public.booking_inventory_allocation a
          where a.inventory_unit_id = u.inventory_unit_id
            and a.released_at is null
            and a.starts_at < ends_at_value
            and a.ends_at > starts_at_value
        )
      order by u.inventory_unit_id
      limit required_units
    loop
      insert into public.booking_inventory_allocation (booking_id, inventory_unit_id, starts_at, ends_at)
      values (booking_id_value, selected_unit, starts_at_value, ends_at_value);
      allocated_units := allocated_units + 1;
    end loop;
    if allocated_units <> required_units then
      raise exception 'Only % table(s) remain available for this meal period', allocated_units;
    end if;
  else
    select u.inventory_unit_id into selected_unit
    from public.booking_inventory_unit u
    where u.app_item_key = item_key_value
      and u.unit_label = unit_label_value
      and u.active;
    if selected_unit is null then
      raise exception 'The selected unit is not part of this item';
    end if;
    if exists (
      select 1 from public.booking_inventory_allocation a
      where a.inventory_unit_id = selected_unit
        and a.released_at is null
        and a.starts_at < ends_at_value
        and a.ends_at > starts_at_value
    ) then
      raise exception 'The selected unit was just booked for those dates; refresh availability and choose another';
    end if;
    insert into public.booking_inventory_allocation (booking_id, inventory_unit_id, starts_at, ends_at)
    values (booking_id_value, selected_unit, starts_at_value, ends_at_value);
  end if;

  insert into public.receipt (
    booking_id, receipt_number, total_amount, downpayment_amount, balance_amount
  )
  values (booking_id_value, receipt_number_value, total_value, fee_value, balance_value);

  insert into public.payment (booking_id, amount, payment_type, payment_status)
  values (booking_id_value, fee_value, payment_method, 'pending');

  return booking_data;
end;
$$;

create or replace function public.cancel_customer_booking(p_booking_id text)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  if auth.uid() is null then
    raise exception 'Sign in is required';
  end if;

  update public.bookings
  set booking_status = 'cancelled',
      cancelled_at = clock_timestamp()
  where id = p_booking_id
    and user_id = auth.uid()::text
    and booking_status = 'ongoing'
    and start_at > now();

  if not found then
    raise exception 'Booking not found or it can no longer be cancelled';
  end if;

  update public.booking_inventory_allocation
  set released_at = clock_timestamp()
  where booking_id = p_booking_id and released_at is null;

  update public.payment
  set payment_status = 'cancelled'
  where booking_id = p_booking_id and payment_status = 'pending';
end;
$$;

create or replace function public.complete_customer_booking(p_booking_id text)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  if auth.uid() is null then
    raise exception 'Sign in is required';
  end if;

  update public.bookings
  set completed = true,
      booking_status = 'completed',
      completed_at = clock_timestamp()
  where id = p_booking_id
    and user_id = auth.uid()::text
    and booking_status = 'ongoing'
    and end_at <= now();

  if not found then
    raise exception 'Only an ended booking can be marked complete';
  end if;
end;
$$;

