-- Carry current non-cancelled bookings into the new allocation model. If the
-- existing JSON cannot identify its booked unit/date, fail rather than silently
-- making that inventory appear available.
do $$
declare
  existing_booking record;
  item_key_value text;
  category_value text;
  unit_label_value text;
  reservation_date date;
  check_in date;
  check_out date;
  starts_at_value timestamptz;
  ends_at_value timestamptz;
  start_time_value time;
  end_time_value time;
  required_units integer;
  allocated_units integer;
  selected_unit bigint;
  conflicting_booking_id text;
begin
  for existing_booking in
    select b.id, b.booking_status, b.data
    from public.bookings b
    where b.booking_status = 'ongoing'
      and not b.completed
    order by b.created_at, b.id
  loop
    item_key_value := existing_booking.data ->> 'itemId';
    category_value := existing_booking.data ->> 'category';

    if item_key_value is null or category_value is null then
      raise exception 'Cannot safely migrate booking %: item or category is missing', existing_booking.id;
    end if;

    if category_value in ('room', 'cottage') then
      check_in := nullif(existing_booking.data ->> 'checkIn', '')::date;
      check_out := nullif(existing_booking.data ->> 'checkOut', '')::date;
      unit_label_value := nullif(existing_booking.data ->> 'unitLabel', '');
      if check_in is null or check_out is null or check_out <= check_in or unit_label_value is null then
        raise exception 'Cannot safely migrate booking %: stay dates or assigned unit are missing', existing_booking.id;
      end if;
      starts_at_value := check_in::timestamp at time zone 'Asia/Manila';
      ends_at_value := check_out::timestamp at time zone 'Asia/Manila';
      if ends_at_value <= now() then
        continue;
      end if;

      select u.inventory_unit_id into selected_unit
      from public.booking_inventory_unit u
      where u.app_item_key = item_key_value
        and u.unit_label = unit_label_value
        and u.active;
      if selected_unit is null then
        raise exception 'Cannot safely migrate booking %: unit % is not in the existing inventory', existing_booking.id, unit_label_value;
      end if;

      select a.booking_id into conflicting_booking_id
      from public.booking_inventory_allocation a
      where a.inventory_unit_id = selected_unit
        and a.released_at is null
        and a.starts_at < ends_at_value
        and a.ends_at > starts_at_value
      order by a.starts_at, a.booking_id
      limit 1;
      if conflicting_booking_id is not null then
        raise exception 'Cannot safely migrate booking %: inventory unit % overlaps active booking %; resolve the conflicting reservation before retrying',
          existing_booking.id, unit_label_value, conflicting_booking_id;
      end if;

      insert into public.booking_inventory_allocation (booking_id, inventory_unit_id, starts_at, ends_at)
      values (existing_booking.id, selected_unit, starts_at_value, ends_at_value);

    elsif category_value = 'restaurant' then
      reservation_date := nullif(existing_booking.data ->> 'resDate', '')::date;
      if reservation_date is null then
        raise exception 'Cannot safely migrate booking %: restaurant date is missing', existing_booking.id;
      end if;
      case item_key_value
        when 'breakfast' then start_time_value := time '06:00'; end_time_value := time '10:00';
        when 'lunch' then start_time_value := time '11:00'; end_time_value := time '14:30';
        when 'dinner' then start_time_value := time '18:00'; end_time_value := time '22:00';
        else raise exception 'Cannot safely migrate booking %: unknown restaurant item %', existing_booking.id, item_key_value;
      end case;
      starts_at_value := (reservation_date + start_time_value)::timestamp at time zone 'Asia/Manila';
      ends_at_value := (reservation_date + end_time_value)::timestamp at time zone 'Asia/Manila';
      if ends_at_value <= now() then
        continue;
      end if;
      if existing_booking.data ->> 'resType' = 'Whole Restaurant' then
        required_units := (select count(*) from public.booking_inventory_unit u where u.app_item_key = item_key_value and u.active);
      else
        required_units := (existing_booking.data ->> 'tables')::integer;
      end if;
      if required_units < 1 then
        raise exception 'Cannot safely migrate booking %: table count is invalid', existing_booking.id;
      end if;

      allocated_units := 0;
      for selected_unit in
        select u.inventory_unit_id
        from public.booking_inventory_unit u
        where u.app_item_key = item_key_value
          and u.active
          and not exists (
            select 1 from public.booking_inventory_allocation a
            where a.inventory_unit_id = u.inventory_unit_id
              and a.released_at is null
              and a.starts_at < ends_at_value
              and a.ends_at > starts_at_value
          )
        order by u.inventory_unit_id
        limit required_units
      loop
        insert into public.booking_inventory_allocation (booking_id, inventory_unit_id, starts_at, ends_at)
        values (existing_booking.id, selected_unit, starts_at_value, ends_at_value);
        allocated_units := allocated_units + 1;
      end loop;
      if allocated_units <> required_units then
        raise exception 'Cannot safely migrate booking %: requested % tables but only % are available', existing_booking.id, required_units, allocated_units;
      end if;

    elsif category_value = 'venue' then
      reservation_date := nullif(existing_booking.data ->> 'resDate', '')::date;
      start_time_value := nullif(existing_booking.data ->> 'startTime', '')::time;
      end_time_value := nullif(existing_booking.data ->> 'endTime', '')::time;
      unit_label_value := nullif(existing_booking.data ->> 'unitLabel', '');
      if reservation_date is null or start_time_value is null or end_time_value is null
        or end_time_value <= start_time_value or unit_label_value is null then
        raise exception 'Cannot safely migrate booking %: event date, times, or assigned unit are missing', existing_booking.id;
      end if;
      starts_at_value := (reservation_date + start_time_value)::timestamp at time zone 'Asia/Manila';
      ends_at_value := (reservation_date + end_time_value)::timestamp at time zone 'Asia/Manila';
      if ends_at_value <= now() then
        continue;
      end if;
      select u.inventory_unit_id into selected_unit
      from public.booking_inventory_unit u
      where u.app_item_key = item_key_value
        and u.unit_label = unit_label_value
        and u.active;
      if selected_unit is null then
        raise exception 'Cannot safely migrate booking %: venue unit % is not in the existing inventory', existing_booking.id, unit_label_value;
      end if;
      if exists (
        select 1 from public.booking_inventory_allocation a
        where a.inventory_unit_id = selected_unit
          and a.released_at is null
          and a.starts_at < ends_at_value
          and a.ends_at > starts_at_value
      ) then
        raise exception 'Cannot safely migrate booking %: venue unit % has an overlapping existing booking', existing_booking.id, unit_label_value;
      end if;
      insert into public.booking_inventory_allocation (booking_id, inventory_unit_id, starts_at, ends_at)
      values (existing_booking.id, selected_unit, starts_at_value, ends_at_value);
    else
      raise exception 'Cannot safely migrate booking %: unsupported category %', existing_booking.id, category_value;
    end if;
  end loop;
end;
$$;

